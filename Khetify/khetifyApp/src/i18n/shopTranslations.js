export const dictionaries = { en, hi };

/**
 * Look up `key` in `lang`, falling back to English and then to the key itself.
 *
 * The fallback chain is the point: a key that has not been given a Hindi value
 * yet renders its English string rather than a blank space or a raw key, so the
 * storefront stays usable while translation is still being filled in.
 */
export function translate(lang, key, vars) {
  const value = dictionaries[lang]?.[key] ?? dictionaries[DEFAULT_LANGUAGE][key] ?? key;
  if (!vars) return value;
  return Object.keys(vars).reduce(
    (out, name) => out.replaceAll(`{${name}}`, vars[name] ?? ""),
    value
  );
}